#!/usr/bin/env python3
"""⛰️ Steep slopes on one country's travel roads — from the Copernicus DEM.

  reads  data/<cc>/travelRoads.ts            (~1 point per km of road)
  reads  Copernicus DEM GLO-90 (AWS Open Data, free, no key) — one 1°×1° tile at a time
  writes data/<cc>/steepSlopes.ts            midpoints where the road climbs or drops
         ≥ 6 % over 0.7–1.5 km  (the same rule as the private repo's geo-slopes.mjs)

Heights: © DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018,
provided under COPERNICUS by the European Union and ESA; all rights reserved.
Usage: slopes.py <CC>   → STATUS=DONE / STATUS=FAILED
"""

import math
import os
import re
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

DEM = "https://copernicus-dem-90m.s3.amazonaws.com"
GRADE = 0.06


def log(*a):
    print(*a, flush=True)


def finish(status):
    log(f"STATUS={status}")
    sys.exit(0 if status != "FAILED" else 1)


def tile_name(la, lo):
    ns = f"N{la:02d}" if la >= 0 else f"S{-la:02d}"
    ew = f"E{lo:03d}" if lo >= 0 else f"W{-lo:03d}"
    name = f"Copernicus_DSM_COG_30_{ns}_00_{ew}_00_DEM"
    return f"{DEM}/{name}/{name}.tif"


def exists(url):
    for t in range(3):
        try:
            urllib.request.urlopen(urllib.request.Request(url, method="HEAD"), timeout=60)
            return True
        except urllib.error.HTTPError as e:
            if e.code in (403, 404):
                return False  # no tile = open sea
        except Exception:  # noqa: BLE001 — network hiccup, try again
            pass
    raise RuntimeError(f"cannot reach {url}")


def heights_for(tile, pts):
    import rasterio
    url = tile_name(*tile)
    if not exists(url):
        return {p: 0.0 for p in pts}
    with rasterio.open(url) as ds:
        band = ds.read(1)
        out = {}
        for la, lo in pts:
            r, c = ds.index(lo, la)
            r = min(max(r, 0), band.shape[0] - 1)
            c = min(max(c, 0), band.shape[1] - 1)
            out[(la, lo)] = round(float(band[r, c]), 1)
        return out


def main(cc):
    path = f"data/{cc.lower()}/travelRoads.ts"
    if not os.path.exists(path):
        log(f"::error::{path} missing — the roads job for {cc} runs first.")
        finish("FAILED")
    points = [(float(a), float(b)) for a, b in re.findall(r"\[(-?\d+(?:\.\d+)?), (-?\d+(?:\.\d+)?)\]", open(path, encoding="utf8").read())]
    tiles = {}
    for p in points:
        tiles.setdefault((math.floor(p[0]), math.floor(p[1])), []).append(p)
    log(f"{cc} slopes: {len(points)} road points on {len(tiles)} DEM tiles")
    heights = {}
    with ThreadPoolExecutor(8) as pool:
        for part in pool.map(lambda kv: heights_for(kv[0], kv[1]), tiles.items()):
            heights.update(part)

    # Grade to neighbours 0.7–1.5 km away (same maths as geo-slopes.mjs).
    R = 6_371_000
    rad = math.radians

    def dist(a, b):
        return R * math.hypot(rad(b[0] - a[0]), rad(b[1] - a[1]) * math.cos(rad((a[0] + b[0]) / 2)))

    def cell(p):
        return (math.floor(p[0] / 0.01), math.floor(p[1] / 0.01))

    grid = {}
    for p in points:
        grid.setdefault(cell(p), []).append(p)
    seen, slopes = set(), []
    for p in points:
        e = heights[p]
        r, c = cell(p)
        for dr in range(-2, 3):
            for dc in range(-2, 3):
                for q in grid.get((r + dr, c + dc), ()):
                    d = dist(p, q)
                    if d < 700 or d > 1500 or abs(e - heights[q]) / d < GRADE:
                        continue
                    mid = (math.floor((p[0] + q[0]) / 2 * 1e4 + 0.5) / 1e4, math.floor((p[1] + q[1]) / 2 * 1e4 + 0.5) / 1e4)
                    k = (math.floor(mid[0] / 0.005), math.floor(mid[1] / 0.005))
                    if k in seen:
                        continue
                    seen.add(k)
                    slopes.append(mid)
    slopes.sort()
    where = "Saudi Arabia" if cc == "SA" else cc
    geo = "../geo" if cc == "SA" else "../../../geo"
    os.makedirs(f"data/{cc.lower()}", exist_ok=True)
    with open(f"data/{cc.lower()}/steepSlopes.ts", "w", encoding="utf8") as f:
        f.write(f"""// ⚠️ Steep slopes (≥ 6 % over ~1 km) on travel roads in {where} — [latitude, longitude].
//
// GENERATED by safewithus-map-data/scripts/slopes.py — do not edit by hand.
// Roads © OpenStreetMap contributors, ODbL; heights: Copernicus DEM GLO-90 (© DLR e.V. 2010-2014 and
// © Airbus Defence and Space GmbH 2014-2018, provided under COPERNICUS by the European Union and ESA).
//
// {len(slopes)} points.
import type {{ LatLon }} from '{geo}';

export const STEEP_SLOPES: ReadonlyArray<LatLon> = [
""" + "".join(f"  [{fmt(a)}, {fmt(b)}],\n" for a, b in slopes) + "];\n")
    log(f"✅ steepSlopes for {cc}: {len(slopes)} points")
    finish("DONE")


def fmt(v):
    return str(int(v)) if float(v).is_integer() else repr(v)


if __name__ == "__main__":
    try:
        main(sys.argv[1].upper())
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        log(f"::error::{type(e).__name__}: {e}")
        finish("FAILED")
